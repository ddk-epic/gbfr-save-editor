// Usage: pnpm gen:data [tables.sqlite] [text dir]
// Generates each package's data.gen.ts and the facade's text/ from the game tables.
import { writeFileSync } from "node:fs";
import { OUTPUT, createContext } from "./gen/context";
import { genCharacter } from "./gen/character";
import { genConflux } from "./gen/conflux";
import { genFateEpisode } from "./gen/fate-episode";
import { genItem } from "./gen/item";
import { genJournal } from "./gen/journal";
import { genKeys } from "./gen/keys";
import { genMasterTrait } from "./gen/master-trait";
import { genMastery } from "./gen/mastery";
import { genOverMastery } from "./gen/over-mastery";
import { genQuest } from "./gen/quest";
import { genSigil } from "./gen/sigil";
import { genSummon } from "./gen/summon";
import { genText } from "./gen/text";
import { genTrait } from "./gen/trait";
import { genTrophy } from "./gen/trophy";
import { genWeapon } from "./gen/weapon";

const [
  dbPath = "../gbfr-extract/tables.sqlite",
  textDir = "../gbfr-extract/system/table/text",
] = process.argv.slice(2);

const { ctx, blocks } = createContext(dbPath, textDir);

// Keys open each file; text fills the names the domains comment with.
genKeys(ctx);
genText(ctx);
genCharacter(ctx);
genConflux(ctx);
genFateEpisode(ctx);
genItem(ctx);
genJournal(ctx);
genMasterTrait(ctx);
genMastery(ctx);
genOverMastery(ctx);
genQuest(ctx);
genSigil(ctx);
genSummon(ctx);
genTrait(ctx);
genTrophy(ctx);
genWeapon(ctx);

for (const [file, fileBlocks] of blocks) {
  const out = new URL(`../${OUTPUT[file]}`, import.meta.url);
  writeFileSync(
    out,
    `// Generated by scripts/gen-data.ts from the game archive tables. Do not edit.\n\n${fileBlocks.join("\n\n")}\n`,
  );
}
